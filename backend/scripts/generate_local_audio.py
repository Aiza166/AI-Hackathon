"""Pre-generate Sindhi and Punjabi (Shahmukhi) citizen audio with ElevenLabs eleven_v3.

Reads the fixed text packs (frontend/src/i18n/sd.ts, pa.ts), maps every spoken audio key to
its pack line, writes frontend/public/audio/<lang>/<audioKey>.mp3 and regenerates
frontend/src/i18n/audioClips.ts. Idempotent: existing clips are skipped.

    python scripts/generate_local_audio.py --dry-run          # list keys and character counts
    python scripts/generate_local_audio.py --only prompt_dob  # one test clip per language
    python scripts/generate_local_audio.py                    # everything missing

ELEVENLABS_API_KEY comes from the environment or backend/.env. It is never printed.
"""

import argparse
import json
import os
import re
import shutil
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKS = ROOT / "frontend" / "src" / "i18n"
AUDIO = ROOT / "frontend" / "public" / "audio"
ENV_FILE = ROOT / "backend" / ".env"
VOICE_ID = "EXAVITQu4vr4xnSDxMaL"  # Sarah, premade
MODEL_ID = "eleven_v3"
OUTPUT_FORMAT = "mp3_22050_32"
LANGS = ("sd", "pa")
PAUSE_SECONDS = 0.6

PROMPTS = ("relation", "dob", "deceased", "deceased_cnic", "documents", "account", "review")
STATUS_HEADS = {
    "auto_approved": "head.approved",
    "approved": "head.approved",
    "proof_requested": "head.proof_requested",
    "in_review": "head.in_review",
    "rejected": "head.rejected",
    "withdrawn": "head.withdrawn",
}
SCAM_VERDICTS = ("LIKELY_SCAM", "NOT_SURE", "LOOKS_GENUINE")
LINE = re.compile(r"""^\s*(?:'([^']+)'|([A-Za-z_]\w*))\s*:\s*'((?:[^'\\]|\\.)*)'\s*,\s*$""")


def load_pack(lang: str) -> dict[str, str]:
    pack: dict[str, str] = {}
    for line in (PACKS / f"{lang}.ts").read_text(encoding="utf-8").splitlines():
        m = LINE.match(line)
        if m:
            pack[m.group(1) or m.group(2)] = m.group(3).replace("\\'", "'")
    return pack


def spoken_map(pack: dict[str, str]) -> dict[str, str]:
    """audioKey -> pack key, for every spoken key (missing pack lines are reported)."""
    mapping = {f"prompt_{p}": f"prompt_{p}" for p in PROMPTS}
    mapping.update({f"status_{s}": head for s, head in STATUS_HEADS.items()})
    codes = [k.split(".", 1)[1] for k in pack if k.startswith("reason.")]
    mapping.update({f"reason_{c.lower()}": f"reason.{c}" for c in codes})
    mapping.update({f"scam_{v.lower()}": f"scam.{v}" for v in SCAM_VERDICTS})
    return mapping


def read_key(env_file: Path = ENV_FILE) -> str:
    key = os.environ.get("ELEVENLABS_API_KEY", "")
    if not key and env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("ELEVENLABS_API_KEY="):
                key = line.split("=", 1)[1].strip().strip("'\"")
    if not key:
        sys.exit("ELEVENLABS_API_KEY not found in the environment or backend/.env")
    return key


def synthesize(api_key: str, text: str, lang: str, with_language: bool) -> bytes:
    body = {"text": text, "model_id": MODEL_ID}
    if with_language:
        body["language_code"] = lang
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE_ID}?output_format={OUTPUT_FORMAT}"
    req = urllib.request.Request(
        url,
        data=json.dumps(body).encode("utf-8"),
        headers={"xi-api-key": api_key, "Content-Type": "application/json", "Accept": "audio/mpeg"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read()


def fetch_clip(api_key: str, text: str, lang: str, state: dict) -> bytes:
    try:
        return synthesize(api_key, text, lang, state["with_language"])
    except urllib.error.HTTPError as err:
        detail = err.read().decode("utf-8", "replace")[:300]
        if err.code in (401, 402, 429):
            sys.exit(f"Stopped: HTTP {err.code} from ElevenLabs (auth, credits or rate limit). {detail}")
        if err.code in (400, 422) and state["with_language"]:
            print(f"language_code rejected ({err.code}); retrying without it. {detail}")
            state["with_language"] = False
            return synthesize(api_key, text, lang, False)
        sys.exit(f"Stopped: HTTP {err.code}. {detail}")


def write_clips_module() -> None:
    lines = [
        "// Generated by backend/scripts/generate_local_audio.py. Do not edit.",
        "",
        "export const CLIPS: Record<'sd' | 'pa', ReadonlySet<string>> = {",
    ]
    for lang in LANGS:
        keys = sorted(p.stem for p in (AUDIO / lang).glob("*.mp3"))
        lines.append(f"  {lang}: new Set([{', '.join(repr(k) for k in keys)}]),")
    lines += ["}", ""]
    (PACKS / "audioClips.ts").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--env-file", type=Path, default=ENV_FILE)
    ap.add_argument("--only", help="generate just this audio key (both languages)")
    args = ap.parse_args()

    api_key = "" if args.dry_run else read_key(args.env_file)
    state = {"with_language": True}
    total_chars = 0
    for lang in LANGS:
        pack = load_pack(lang)
        mapping = spoken_map(pack)
        todo = {a: pack[p] for a, p in mapping.items() if p in pack and (not args.only or a == args.only)}
        missing = [a for a, p in mapping.items() if p not in pack]
        (AUDIO / lang).mkdir(parents=True, exist_ok=True)
        print(f"{lang}: {len(todo)} keys, {sum(len(t) for t in todo.values())} chars; no pack text: {missing}")
        done_text: dict[str, Path] = {}
        for audio_key, text in todo.items():
            out = AUDIO / lang / f"{audio_key}.mp3"
            if out.exists() or args.dry_run:
                continue
            twin = done_text.get(text)
            if twin:
                shutil.copyfile(twin, out)
                continue
            out.write_bytes(fetch_clip(api_key, text, lang, state))
            done_text[text] = out
            total_chars += len(text)
            print(f"  wrote {lang}/{audio_key}.mp3 ({out.stat().st_size} bytes)")
            time.sleep(PAUSE_SECONDS)
    if not args.dry_run:
        write_clips_module()
        print(f"characters sent this run: {total_chars}")


if __name__ == "__main__":
    main()
